#!/usr/bin/env bash
set -uo pipefail
cd "$(dirname "$0")/.."

OUT=.proof/pipeline.md
DEMUCS_PORT=${DEMUCS_PORT:-5290}
FALLBACK_PORT=${FALLBACK_PORT:-5291}
RICK='https://www.youtube.com/watch?v=dQw4w9WgXcQ'
mkdir -p .proof .cache/proof

record() {
  local title=$1; shift
  echo "running: $title" >&2
  {
    printf '\n### %s\n\n```console\n$ %s\n' "$title" "$*"
    bash -c "$*" 2>&1 | grep -v -E '^$|^=+$|Hi, looks like you are running TensorFlow.js in Node|ExperimentalWarning|--trace-warnings'
    printf '```\n'
  } >>"$OUT"
}

note() { printf '\n%s\n' "$*" >>"$OUT"; }

wait_for() {
  for _ in $(seq 1 100); do curl -s -o /dev/null "localhost:$1/models/basic-pitch/model.json" && return 0; sleep 0.2; done
  echo "server on $1 did not start" >&2
  exit 1
}

PORT=$DEMUCS_PORT node server/index.js --dev >.cache/proof/server-demucs.log 2>&1 &
DEMUCS_PID=$!
TROWA_DEMUCS=off PORT=$FALLBACK_PORT node server/index.js --dev >.cache/proof/server-fallback.log 2>&1 &
FALLBACK_PID=$!
trap 'kill $DEMUCS_PID $FALLBACK_PID 2>/dev/null' EXIT
wait_for "$DEMUCS_PORT"
wait_for "$FALLBACK_PORT"

cat >"$OUT" <<EOF
# Trowa pipeline proof

Generated by \`scripts/proof.sh\` on $(date -u '+%Y-%m-%d %H:%M UTC') at commit \`$(git rev-parse --short HEAD)\`$(git diff --quiet HEAD -- src server scripts || echo ' (with uncommitted changes)').
Two servers run during the proof: port $DEMUCS_PORT with Demucs enabled, port $FALLBACK_PORT with \`TROWA_DEMUCS=off\` (the path a machine without Demucs takes).

## Unit tests
EOF
record 'vitest' 'npx vitest run 2>&1 | tail -6'

note '## (a) YouTube info endpoint'
for url in "$RICK" 'https://youtu.be/dQw4w9WgXcQ?si=share' 'https://www.youtube.com/watch?v=yZIXLfi8CZQ' \
  'https://www.youtube.com/watch?v=aaaaaaaaaaa' 'https://www.youtube.com/watch?v=eQcmzGIKrzg' 'https://vimeo.com/76979871'; do
  record "info $url" "curl -s -w ' HTTP %{http_code}\n' 'localhost:$DEMUCS_PORT/api/youtube/info?url=$url'"
done

note '## (b) YouTube audio download (first request downloads and converts, second is served from .cache/youtube)'
rm -f .cache/youtube/dQw4w9WgXcQ.wav
record 'audio download' "curl -s -o .cache/proof/rick.wav -w 'HTTP %{http_code}, %{size_download} bytes, %{time_total}s\n' 'localhost:$DEMUCS_PORT/api/youtube/audio?url=$RICK' && ffprobe -v error -show_entries format=duration:stream=codec_name,sample_rate,channels -of default=nw=1 .cache/proof/rick.wav"
record 'audio cached' "curl -s -o /dev/null -w 'HTTP %{http_code}, %{size_download} bytes, %{time_total}s\n' 'localhost:$DEMUCS_PORT/api/youtube/audio?url=$RICK'"

note '## (c) Known melody: Twinkle Twinkle in C, 100 bpm, 4/4'
note 'Expected, one bar per line (note/16ths): C C G G | A A G/8 | F F E E | D D C/8 | G G F F | E E D/8 | G G F F | E E D/8 | then bars 1-4 again. Every quarter note is 4 sixteenths.'
record 'synthesize fixtures' 'npx tsx scripts/fixtures.ts .proof/fixtures'
record 'twinkle, Demucs absent (filter fallback)' "npx tsx scripts/transcribe.ts .proof/fixtures/twinkle.wav --server http://localhost:$FALLBACK_PORT --title 'Twinkle Twinkle Little Star' --out .proof/twinkle.musicxml"
record 'twinkle plus bass accompaniment, filter fallback' "npx tsx scripts/transcribe.ts .proof/fixtures/twinkle-with-bass.wav --server http://localhost:$FALLBACK_PORT"
record 'twinkle plus bass accompaniment, Demucs' "npx tsx scripts/transcribe.ts .proof/fixtures/twinkle-with-bass.wav --server http://localhost:$DEMUCS_PORT"
record 'drums only' "npx tsx scripts/transcribe.ts .proof/fixtures/drums.wav --server http://localhost:$FALLBACK_PORT"
record 'white noise' "npx tsx scripts/transcribe.ts .proof/fixtures/noise.wav --server http://localhost:$FALLBACK_PORT"

note '## MusicXML validity'
if [ ! -f .cache/xsd/musicxml.xsd ]; then
  mkdir -p .cache/xsd
  for f in musicxml.xsd xlink.xsd xml.xsd; do curl -sfL -o ".cache/xsd/$f" "https://raw.githubusercontent.com/w3c/musicxml/v4.0/schema/$f"; done
  sed -i '' 's#http://www.musicxml.org/xsd/xml.xsd#xml.xsd#; s#http://www.musicxml.org/xsd/xlink.xsd#xlink.xsd#' .cache/xsd/musicxml.xsd
fi
record 'validate against the MusicXML 4.0 XSD' 'xmllint --noout --schema .cache/xsd/musicxml.xsd .proof/twinkle.musicxml'

note '## (d) Real YouTube audio'
record 'Rick Astley, Demucs' "npx tsx scripts/transcribe.ts .cache/proof/rick.wav --server http://localhost:$DEMUCS_PORT --title 'Never Gonna Give You Up' --out .proof/rick-demucs.musicxml"
record 'Rick Astley, filter fallback' "npx tsx scripts/transcribe.ts .cache/proof/rick.wav --server http://localhost:$FALLBACK_PORT --title 'Never Gonna Give You Up' --out .proof/rick-fallback.musicxml"
record 'validate the real-song MusicXML' 'xmllint --noout --schema .cache/xsd/musicxml.xsd .proof/rick-demucs.musicxml .proof/rick-fallback.musicxml'

note '## (e) Which separation ran'
record 'server logs' "grep -h separate .cache/proof/server-*.log; echo \"fallback server: \$(grep -c . .cache/proof/server-fallback.log) log lines, no demucs runs\""

note '## Browser (headless Chrome, WebGL tfjs backend, real runPipeline from src/pipeline/index.ts, MusicXML rendered by OpenSheetMusicDisplay)'
head -c 50000 /dev/urandom >.cache/proof/garbage.mp3
ffmpeg -loglevel error -y -f lavfi -i anullsrc=r=8000:cl=mono -t 540 .cache/proof/nine-minutes.wav
harness() { echo "http://localhost:$1/scripts/browser-harness.html?$2"; }
filter='grep -v -E "console.debug|Failed to load resource|vite"'
record 'lookupYoutube' "node scripts/browser-check.mjs '$(harness "$FALLBACK_PORT" mode=lookup)' | $filter"
record 'twinkle with bass, Demucs absent' "node scripts/browser-check.mjs '$(harness "$FALLBACK_PORT" wav=/.proof/fixtures/twinkle-with-bass.wav)' .proof/browser-twinkle.png | $filter"
record 'twinkle with bass, Demucs' "node scripts/browser-check.mjs '$(harness "$DEMUCS_PORT" wav=/.proof/fixtures/twinkle-with-bass.wav)' | $filter"
record 'twinkle transposed +2 (D major)' "node scripts/browser-check.mjs '$(harness "$FALLBACK_PORT" 'wav=/.proof/fixtures/twinkle.wav&transpose=2')' .proof/browser-twinkle-transposed.png | $filter"
record 'drums only' "node scripts/browser-check.mjs '$(harness "$FALLBACK_PORT" wav=/.proof/fixtures/drums.wav)' | $filter"
record 'undecodable file' "node scripts/browser-check.mjs '$(harness "$FALLBACK_PORT" wav=/.cache/proof/garbage.mp3)' | $filter"
record 'nine-minute file' "node scripts/browser-check.mjs '$(harness "$FALLBACK_PORT" wav=/.cache/proof/nine-minutes.wav)' | $filter"
record 'abort during pitch detection' "node scripts/browser-check.mjs '$(harness "$FALLBACK_PORT" mode=abort)' | $filter"
record 'real song in the browser, Demucs' "node scripts/browser-check.mjs '$(harness "$DEMUCS_PORT" wav=/.cache/proof/rick.wav)' .proof/browser-rick.png | $filter"

note '## Mutation checks (each guarded behavior broken on purpose; the guarding test must fail)'
record 'mutations' 'bash scripts/mutation-check.sh'

echo "wrote $OUT" >&2
